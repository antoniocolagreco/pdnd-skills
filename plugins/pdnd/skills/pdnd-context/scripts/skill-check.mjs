#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const skillDir = dirname(dirname(fileURLToPath(import.meta.url)));
const indexPath = join(skillDir, "references", "package-index.md");
const mode = process.argv[2] ?? "check";

const repo = execFileSync("git", ["rev-parse", "--show-toplevel"], {
  encoding: "utf8",
}).trim();

const trackedFiles = execFileSync("git", ["ls-files"], {
  cwd: repo,
  encoding: "utf8",
  maxBuffer: 256 * 1024 * 1024,
})
  .split("\n")
  .filter(Boolean);
const trackedSet = new Set(trackedFiles);

const packages = trackedFiles
  .map((file) => /^packages\/([^/]+)\/package\.json$/.exec(file)?.[1])
  .filter(Boolean)
  .sort();

const kindOf = (pkg) => {
  if (!trackedSet.has(`packages/${pkg}/Dockerfile`)) {
    return "library";
  }
  const indexFile = join(repo, "packages", pkg, "src", "index.ts");
  const source = existsSync(indexFile) ? readFileSync(indexFile, "utf8") : "";
  if (/\b(runConsumer|runBatchConsumer)\b/.test(source)) {
    return "consumer";
  }
  if (/\bstartServer\b/.test(source)) {
    return "http";
  }
  return "job";
};

const guideOf = (pkg, kind) => {
  if (kind === "library") {
    return "shared-libraries";
  }
  if (kind === "http") {
    if (pkg === "backend-for-frontend") {
      return "bff";
    }
    if (pkg.includes("gateway")) {
      return "gateway";
    }
    if (pkg.endsWith("-process") || pkg.endsWith("-manager")) {
      return "process-service";
    }
    return "none";
  }
  if (kind === "consumer") {
    if (pkg.endsWith("-readmodel-writer-sql")) {
      return "sql-readmodel-writer";
    }
    if (pkg.endsWith("-platformstate-writer")) {
      return "platformstate-writer";
    }
    if (pkg.endsWith("-outbound-writer")) {
      return "outbound-writer";
    }
    return "event-dispatcher";
  }
  return pkg.endsWith("-importer") ? "importer" : "scheduled-job";
};

const vitestConfigsOf = (pkg) => {
  const hasTests = trackedFiles.some((file) =>
    file.startsWith(`packages/${pkg}/test/`)
  );
  if (!hasTests) {
    return "no tests";
  }
  const labels = [
    ["vitest.config.ts", "default"],
    ["vitest.api.config.ts", "api"],
    ["vitest.integration.config.ts", "integration"],
  ]
    .filter(([file]) => trackedSet.has(`packages/${pkg}/${file}`))
    .map(([, label]) => label);
  return labels.length > 0 ? labels.join(", ") : "default";
};

const filterNameOf = (pkg) => {
  const { name } = JSON.parse(
    readFileSync(join(repo, "packages", pkg, "package.json"), "utf8")
  );
  return name === `pagopa-interop-${pkg}` ? "" : `\`${name}\``;
};

const buildIndex = () => {
  const rows = packages.map((pkg) => {
    const kind = kindOf(pkg);
    return `| \`${pkg}\` | ${kind} | ${guideOf(pkg, kind)} | ${vitestConfigsOf(pkg)} | ${filterNameOf(pkg)} |`;
  });
  return [
    "# Package Index",
    "",
    "Generated by `scripts/skill-check.mjs generate`. Do not edit by hand.",
    "",
    "Look up one row with `rg '^\\| `<package>`' references/package-index.md`.",
    "",
    "- Kind: `http` server, `consumer` (runs until stopped), `job` (runs once and exits), `library` (no process).",
    "- Guide: the file to read in `references/package-types/`. `none` means read the package source.",
    "- Tests: the Vitest configs. The commands for each are in `SKILL.md`.",
    "- Filter name: filled only when it differs from `pagopa-interop-<package>`.",
    "",
    "| Package | Kind | Guide | Tests | Filter name |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
};

const walk = (dir) =>
  readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });

const docFiles = walk(skillDir).filter((file) => file.endsWith(".md"));
const proseOf = (text) => text.replace(/```[\s\S]*?```/g, "");
const backticked = (text) =>
  [...text.matchAll(/`([^`\n]+)`/g)].map((match) => match[1]);

const repoIdentifiers = () => {
  const identifiers = new Set();
  const codeFile = /\.(ts|mjs|yml|yaml|json|sql|proto)$/;
  for (const file of trackedFiles) {
    if (!codeFile.test(file) || file === "pnpm-lock.yaml") {
      continue;
    }
    const full = join(repo, file);
    if (!existsSync(full)) {
      continue;
    }
    const matches = readFileSync(full, "utf8").match(/[A-Za-z_][A-Za-z0-9_]*/g);
    for (const identifier of matches ?? []) {
      identifiers.add(identifier);
    }
  }
  return identifiers;
};

const check = () => {
  const problems = [];
  const report = (file, message) =>
    problems.push(`${relative(skillDir, file)}: ${message}`);

  if (!existsSync(indexPath) || readFileSync(indexPath, "utf8") !== buildIndex()) {
    report(indexPath, "stale, run: skill-check.mjs generate");
  }

  const mapPath = join(skillDir, "references", "package-map.md");
  const mapped = new Set(backticked(readFileSync(mapPath, "utf8")));
  for (const pkg of packages) {
    if (!mapped.has(pkg)) {
      report(mapPath, `package missing: ${pkg}`);
    }
  }

  const skillText = readFileSync(join(skillDir, "SKILL.md"), "utf8");
  for (const file of docFiles) {
    const name = relative(skillDir, file);
    if (
      name.startsWith("references/") &&
      !name.endsWith("package-index.md") &&
      !skillText.includes(name)
    ) {
      report(file, "not linked from SKILL.md");
    }
  }

  const identifiers = repoIdentifiers();
  const hedges =
    /\b(usually|typically|commonly|often|generally|normally|probably|mostly|when applicable|where applicable|if appropriate|as appropriate|as needed|if needed|when needed|if necessary|when relevant|when required|if required)\b/i;
  const pathStart = /^(packages|docker|\.github|collections)(\/|$)/;
  const identifier = /^(?=.*[a-z])[A-Za-z][A-Za-z0-9]*[a-z0-9][A-Z][A-Za-z0-9]*$/;

  for (const file of docFiles) {
    const text = readFileSync(file, "utf8");
    if (text.includes("—")) {
      report(file, "contains an em dash");
    }
    const hedgeMatch = proseOf(text).match(hedges);
    if (hedgeMatch) {
      report(file, `vague wording: ${hedgeMatch[0]}`);
    }
    for (const reference of text.match(/references\/[a-z/-]+\.md/g) ?? []) {
      if (!existsSync(join(skillDir, reference))) {
        report(file, `missing skill file: ${reference}`);
      }
    }
    if (file === indexPath) {
      continue;
    }
    for (const token of backticked(text)) {
      if (pathStart.test(token) && !/[<*{ ]/.test(token)) {
        const path = token.replace(/\/$/, "");
        const exists =
          trackedSet.has(path) ||
          trackedFiles.some((tracked) => tracked.startsWith(`${path}/`));
        if (!exists) {
          report(file, `path not in repo: ${token}`);
        }
      } else if (identifier.test(token) && !identifiers.has(token)) {
        report(file, `symbol not in repo: ${token}`);
      }
    }
  }

  if (problems.length > 0) {
    console.log(problems.join("\n"));
    console.log(`\n${problems.length} problem(s)`);
    process.exit(1);
  }
  console.log(`OK: ${packages.length} packages, ${docFiles.length} files`);
};

if (mode === "generate") {
  writeFileSync(indexPath, buildIndex());
  console.log(`Generated ${relative(skillDir, indexPath)}: ${packages.length} packages`);
} else if (mode === "check") {
  check();
} else {
  console.log("Usage: skill-check.mjs [generate|check]");
  process.exit(1);
}
